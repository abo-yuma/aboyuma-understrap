"use strict";

const process = require("process");

const colors = [
	"blue",
	"indigo",
	"purple",
	"pink",
	"red",
	"orange",
	"yellow",
	"green",
	"teal",
	"cyan",
	"white",
	"gray",
	"gray-dark",
];

/**
 * Bootstrap version detection.
 *
 * - Bootstrap 5 is the default target.
 * - Bootstrap 4 support is kept for Understrap compatibility only.
 */
const BS4 = process.argv[process.argv.length - 1] === "BS4";
/**
 * Bootstrap 5 uses CSS variables prefixed with `--bs-`
 * Bootstrap 4 does not use the prefix.
 */
const colorInfix = BS4 ? "" : "bs-";
/**
 * Output file for Gutenberg editor color palette.
 * This file is autogenerated on every build and should not be tracked in Git.
 */
const output =
	"inc/editor-color-palette" + (BS4 ? "-bootstrap4" : "") + ".json";

module.exports = (ctx) => {
	return {
		map: {
			inline: false,
			/** 
			 * Disabling annotation ensures the generated CSS contains
			 * only valid CSS declarations, keeping the color palette JSON clean
			 * and preventing build errors such as:
			 *   "End of file expected"
			 */
			annotation: false,
			sourcesContent: true,
		},
		plugins: {
			autoprefixer: {
				cascade: false,
				env: BS4 ? "bs4" : "bs5",
			},
			/**
			 * Generates Gutenberg editor color palette from CSS variables.
			 *
			 * Build flow:
			 * Bootstrap defaults
			 *   → Bootswatch overrides
			 *   → SCSS compilation
			 *   → editor-color-palette.json regenerated
			 */
			"postcss-understrap-palette-generator": {
				colors: colors.map((x) => `--${colorInfix}${x}`),
				output: output,
			},
		},
	};
};
